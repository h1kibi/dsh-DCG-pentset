 /**
  * 行为预设的**提示词包**（2026-10-04 决定：预设不再是硬纪律，只注入提示词；
  * 2026-10-05 起预设是每个作业的**必选项**，并按作业场景做差异化）。
  *
  * ── 职责划分 ──
  *
  * 本文件 vs src/agents/phase-profiles.ts 的关系（两者都是提示词分节，维度不同）：
  *   - **本文件（behavior-prompts）**：操作风格与全局约束
  *     └─ 「怎样行为」：隐蔽 / 常规 / 穷尽三档施策
  *     └─ 「什么不做」：默认禁用的动作类别（persistence / destructive / exfiltration）
  *     └─ 「什么时候要人批」：放行模式（auto / human）
  *   - **phase-profiles.ts**：阶段职责与交付边界
  *     └─ 「本阶段做什么」：情报收集 vs 威胁建模 vs 利用验证的具体职责
  *     └─ 「做到哪儿算完」：交付标准与退出条件
  *     └─ 「失败怎么办」：故障回退与补救机制
  *     └─ 「何时检索」：检索策略与触发点
  *
  * 一个 Agent 同时注入两个：预设说「做事的风格和约束」，Profile 说「这个阶段的职责」。
  * 预设是全局的、跨阶段的；Profile 是阶段特定的。
  *
  * ── 为什么改成提示词 ──
  *
  * 当"预设"决定"哪些动作类别被服务端拒绝"时，Agent 会在被拒后反复
  * 试探，或者因为"这一类没开"而放弃本来就合理的动作——而真正的边界应当由**人类放行**
  * 把守，预设只表达意图（要不要安静、覆盖到什么程度、能不能接受噪声）。
  *
  * 因此现在的分工是：
  *   - 预设 → 一段**场景化的行为指引**（本文件），注入每个 worker 会话的提示词；
  *   - 超出预设的动作 → Agent **主动请人类放行**（`pentest_request_action_approval`）；
  *   - 默认禁用类别（persistence / destructive / exfiltration）与逐次放行下限
  *     仍然由服务端硬守——预设措辞不能豁免它们。
  *
  * 三档对应三种作业场景，指引必须**真的不同**（不是同一段话换个形容词）：
  *   `stealth`  红队 / 隐蔽测试——避免被检测是第一优先级，慢但安全
  *   `standard` 常规授权测试——平衡覆盖与噪声，接受合理痕迹以提升效率
  *   `fast`     快速测试 / 时间受限——追求速度，在授权与范围内以最快方式完成
  *   `custom`   人类自己写的指引（逐字注入，冲突时优先于通用口径）
  */

/** 注入所需的最小事实：预设名 + 宿主侧实际生效的节奏上限 + 自定义指引（仅 custom）。 */
export interface BehaviorBrief {
  readonly profile: 'stealth' | 'standard' | 'fast' | 'custom';
  readonly pacing?: Readonly<Record<string, number>>;
  readonly customGuidance?: string;
  /** 该作业冻结的审批模式；省略按 `human`（保守）。 */
  readonly approvalMode?: 'human' | 'auto';
}

/** 场景名（与界面下拉的标签同源语义；界面另有自己的 exhaustiveness 映射）。 */
const PROFILE_SCENARIOS: Readonly<Record<'stealth' | 'standard' | 'fast' | 'custom', string>> = Object.freeze({
  stealth: '红队 / 隐蔽测试',
  standard: '常规授权测试',
  fast: '快速测试 / 时间受限',
  custom: '自定义（人类写指引）',
});

